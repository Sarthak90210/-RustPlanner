"""Export public CurrentState property names/types without nested helper classes.

The original GetItemList reflects properties, not fields or methods. Keep source
order here; Rust applies StringCompareTo's natural ordering for the Status tab.
"""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
src = (root / 'reference/MissionPlanner/ExtLibs/ArduPilot/CurrentState.cs').read_text(encoding='utf-8-sig')
# Blank comments and string literals while preserving character offsets.
clean = re.sub(r'//[^\n]*|/\*[\s\S]*?\*/|@?"(?:""|\\.|[^"\\])*"', lambda m: ' ' * len(m[0]), src)
depth = 0
depths = []
for ch in clean:
    depths.append(depth)
    depth += (ch == '{') - (ch == '}')
properties = []
defaults = []
for m in re.finditer(r'\bpublic\s+(?:static\s+)?([\w.<>?,\[\] ()]+?)\s+(\w+)\s*(?=\{|=>)', clean):
    if depths[m.start()] != 2:
        continue
    typ, name = m.groups()
    if typ in {'class', 'enum', 'struct'}:
        continue
    kind = 'Number' if typ in {'float', 'double', 'byte', 'sbyte', 'short', 'ushort', 'int', 'uint', 'long', 'ulong', 'decimal'} else 'Bool' if typ == 'bool' else 'Text' if typ == 'string' else 'Object'
    properties.append((name, kind))
    # C# auto-properties have a language-defined zero/false default, unless
    # initialized. Computed getters require an explicit port instead.
    auto = re.match(r'\s*\{\s*get;\s*(?:(?:private|protected|internal)\s+)?set;\s*\}', clean[m.end():])
    if auto and kind in {'Number', 'Bool'}:
        tail = clean[m.end() + auto.end():]
        init = re.match(r'\s*=\s*([^;]+);', tail)
        value = 0.0
        if init:
            literal = init[1].strip().rstrip('fFdDmMuUlL')
            if literal in {'true', 'false'}:
                value = float(literal == 'true')
            else:
                try:
                    value = float(literal)
                except ValueError:
                    continue
        defaults.append((name, value))
assert len(properties) > 400 and len(dict(properties)) == len(properties)
out = '// Generated by scripts/export_state_properties.py from GPL-3.0 Mission Planner CurrentState.cs.\n'
out += '#[derive(Clone, Copy, PartialEq, Eq)]\npub enum PropertyKind { Number, Bool, Text, Object }\n'
out += 'pub const PROPERTIES: &[(&str, PropertyKind)] = &[\n'
out += ''.join(f'    ({json.dumps(name)}, PropertyKind::{kind}),\n' for name, kind in properties)
out += '];\n'
out += '\npub const AUTO_DEFAULTS: &[(&str, f64)] = &[\n'
out += ''.join(f'    ({json.dumps(name)}, {value!r}),\n' for name, value in defaults)
out += '];\n'
(root / 'crates/mp-core/src/state_properties.rs').write_text(out, encoding='utf-8')
print(f'Exported {len(properties)} properties, {len(defaults)} source auto-property defaults')

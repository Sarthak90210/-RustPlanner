/// `public struct S`: 7 bytes.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct S {
    pub Vbat: u16,
    pub Battery_Consumption: u16,
    pub RSSI: u8,
    pub Airspeed: u8,
    pub Status: u8,
}

impl S {
    /// `GetMode`: `(mode)(Status >> 2)`, any value.
    pub fn GetMode(&self) -> mode {
        mode((self.Status >> 2) as i32)
    }

    /// `GetFailsafe`
    pub fn GetFailsafe(&self) -> bool {
        (self.Status & 0x2) > 0
    }

    /// `GetArmed`
    pub fn GetArmed(&self) -> bool {
        (self.Status & 0x1) > 0
    }

    fn from_bytes(b: &[u8]) -> S {
        S {
            Vbat: u16::from_le_bytes([b[0], b[1]]),
            Battery_Consumption: u16::from_le_bytes([b[2], b[3]]),
            RSSI: b[4],
            Airspeed: b[5],
            Status: b[6],
        }
    }

    /// Json.NET writes the enum as its number.
    pub fn to_j(&self) -> J {
        J::Obj(vec![
            ("Vbat".into(), J::Int(self.Vbat as i64)),
            ("Battery_Consumption".into(), J::Int(self.Battery_Consumption as i64)),
            ("RSSI".into(), J::Int(self.RSSI as i64)),
            ("Airspeed".into(), J::Int(self.Airspeed as i64)),
            ("Status".into(), J::Int(self.Status as i64)),
            ("GetMode".into(), J::Int(self.GetMode().0 as i64)),
            ("GetFailsafe".into(), J::Bool(self.GetFailsafe())),
            ("GetArmed".into(), J::Bool(self.GetArmed())),
        ])
    }
}


#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::{Arc, Mutex};

    #[test]
    fn recorded_stream_decodes() {
        let mut ltm = LTM::new();
        let gps = Arc::new(Mutex::new(Vec::new()));
        let att = Arc::new(Mutex::new(0));
        let sts = Arc::new(Mutex::new(Vec::new()));
        let (g2, a2, s2) = (gps.clone(), att.clone(), sts.clone());
        ltm.add_new_gps_message(move |g| g2.lock().unwrap().push(*g));
        ltm.add_new_attitude_message(move |_| *a2.lock().unwrap() += 1);
        ltm.add_new_status_message(move |s| s2.lock().unwrap().push(*s));
        for b in TEST_DATA {
            ltm.NewByte(*b);
        }
        let gps = gps.lock().unwrap();
        assert!(!gps.is_empty());
        // first G frame: lat 0xEAEBFDA7, sats/fix 0x2B -> 10 sats, 3D fix
        assert_eq!(gps[0].Latitude, 0xEAEBFDA7u32 as i32);
        assert_eq!((gps[0].GetSats(), gps[0].GetFix()), (10, 3));
        assert!(*att.lock().unwrap() > 0);
        let s = sts.lock().unwrap()[0];
        assert_eq!(s.Vbat, 0x6101);
        // status 0x0D: mode 3, armed, no failsafe
        assert_eq!(s.GetMode(), mode::Horizon);
        assert!(s.GetArmed() && !s.GetFailsafe());
    }
}

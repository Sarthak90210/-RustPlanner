type Handler<T> = Box<dyn FnMut(&T) + Send>;

/// `public class LTM`
pub struct LTM {
    packet: [u8; 100],
    payload: i32,
    crc: u8,
    state: i32,
    /// `event EventHandler<S> NewStatusMessage`
    NewStatusMessage: Vec<Handler<S>>,
    /// `event EventHandler<A> NewAttitudeMessage`
    NewAttitudeMessage: Vec<Handler<A>>,
    /// `event EventHandler<G> NewGPSMessage`
    NewGPSMessage: Vec<Handler<G>>,
}

impl Default for LTM {
    fn default() -> Self {
        LTM {
            packet: [0; 100],
            payload: 0,
            crc: 0,
            state: 0,
            NewStatusMessage: Vec::new(),
            NewAttitudeMessage: Vec::new(),
            NewGPSMessage: Vec::new(),
        }
    }
}

impl LTM {
    pub fn new() -> Self {
        Self::default()
    }

    /// `NewStatusMessage += handler`
    pub fn add_new_status_message(&mut self, h: impl FnMut(&S) + Send + 'static) {
        self.NewStatusMessage.push(Box::new(h));
    }

    /// `NewAttitudeMessage += handler`
    pub fn add_new_attitude_message(&mut self, h: impl FnMut(&A) + Send + 'static) {
        self.NewAttitudeMessage.push(Box::new(h));
    }

    /// `NewGPSMessage += handler`
    pub fn add_new_gps_message(&mut self, h: impl FnMut(&G) + Send + 'static) {
        self.NewGPSMessage.push(Box::new(h));
    }

    /// `test()`: the recorded stream, each message written to the console as indented JSON.
    pub fn test(&mut self) {
        self.add_new_status_message(|s| crate::dotnet::io::console_write_line(&s.to_j().to_indented()));
        self.add_new_attitude_message(|s| crate::dotnet::io::console_write_line(&s.to_j().to_indented()));
        self.add_new_gps_message(|s| crate::dotnet::io::console_write_line(&s.to_j().to_indented()));

        for a in TEST_DATA {
            self.NewByte(*a);
        }
    }

    /// `NewByte(byte data)`: the frame state machine. In state 3 the byte is stored, the
    /// frame's length decides whether it is the checksum (compared with the XOR of the
    /// payload so far), and then it is folded into the XOR either way.
    pub fn NewByte(&mut self, data: u8) {
        match self.state {
            1 => {
                if data == HEADER[1] {
                    self.packet[self.state as usize] = data;
                    self.state += 1;
                } else {
                    self.state = 0;
                }
            }
            2 => {
                self.packet[self.state as usize] = data;
                self.state += 1;
                self.crc = 0;
                self.payload = 0;
            }
            3 => {
                let at = (self.state + self.payload) as usize;
                self.packet[at] = data;
                let len = match self.packet[2] as char {
                    'G' => Some(18),
                    'A' => Some(10),
                    'S' => Some(11),
                    _ => None,
                };
                match len {
                    Some(len) => {
                        if self.state + 1 + self.payload == len {
                            if self.packet[at] == self.crc {
                                self.state = 0;
                                let line = self.packet;
                                self.NewLine(&line);
                            }

                            self.state = 0;
                        }
                    }
                    None => self.state = 0,
                }

                self.crc ^= data;
                self.payload += 1;
            }
            // default: and case 0:
            _ => {
                if data == HEADER[0] {
                    self.packet[self.state as usize] = data;
                    self.state += 1;
                } else {
                    self.state = 0;
                }
            }
        }
    }

    /// `NewLine(byte[] line)`: the payload from byte 3 as the frame's struct.
    fn NewLine(&mut self, line: &[u8]) {
        if line.len() > 3 && line[0] == HEADER[0] && line[1] == HEADER[1] {
            match line[2] as char {
                'G' => {
                    let g = G::from_bytes(&line[3..]);
                    for h in self.NewGPSMessage.iter_mut() {
                        h(&g);
                    }
                }
                'A' => {
                    let a = A::from_bytes(&line[3..]);
                    for h in self.NewAttitudeMessage.iter_mut() {
                        h(&a);
                    }
                }
                'S' => {
                    let s = S::from_bytes(&line[3..]);
                    for h in self.NewStatusMessage.iter_mut() {
                        h(&s);
                    }
                }
                // 'O', 'N', 'X': nothing
                _ => {}
            }
        }
    }
}


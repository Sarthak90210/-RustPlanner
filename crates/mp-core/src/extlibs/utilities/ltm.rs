//! Port of `ExtLibs/Utilities/LTM.cs`
//!
//! LightTelemetry (Ghettostation's one-way protocol for low bitrates): "$T" then a frame type
//! and a little-endian payload with an XOR checksum. G (GPS, 18 bytes), A (attitude, 10) and
//! S (sensors, 11) frames raise their events; the payload structs are `Pack = 1`.
//! `EventHandler<T>`'s sender is this parser, so the handlers get the value only.

#![allow(non_snake_case)]

use crate::dotnet::json::J;

const HEADER: &[u8; 2] = b"$T";

/// `[StructLayout(Sequential, Pack = 1)] public struct G`: 14 bytes.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct G {
    pub Latitude: i32,
    pub Longitude: i32,
    pub GroundSpeed: u8,
    pub Altitude: i32,
    pub Sats_Fix: u8,
}

impl G {
    /// `GetSats`
    pub fn GetSats(&self) -> i32 {
        (self.Sats_Fix >> 2) as i32
    }

    /// `GetFix`
    pub fn GetFix(&self) -> i32 {
        (self.Sats_Fix & 3) as i32
    }

    fn from_bytes(b: &[u8]) -> G {
        G {
            Latitude: i32::from_le_bytes([b[0], b[1], b[2], b[3]]),
            Longitude: i32::from_le_bytes([b[4], b[5], b[6], b[7]]),
            GroundSpeed: b[8],
            Altitude: i32::from_le_bytes([b[9], b[10], b[11], b[12]]),
            Sats_Fix: b[13],
        }
    }

    /// Json.NET's view: the fields, then the get-only properties.
    pub fn to_j(&self) -> J {
        J::Obj(vec![
            ("Latitude".into(), J::Int(self.Latitude as i64)),
            ("Longitude".into(), J::Int(self.Longitude as i64)),
            ("GroundSpeed".into(), J::Int(self.GroundSpeed as i64)),
            ("Altitude".into(), J::Int(self.Altitude as i64)),
            ("Sats_Fix".into(), J::Int(self.Sats_Fix as i64)),
            ("GetSats".into(), J::Int(self.GetSats() as i64)),
            ("GetFix".into(), J::Int(self.GetFix() as i64)),
        ])
    }
}

